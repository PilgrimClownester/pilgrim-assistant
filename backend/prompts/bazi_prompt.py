from pprint import pformat


BAZI_SYSTEM_PROMPT = """
当前处于八字分析模式。你基于本地程序提供的八字排盘结构化数据进行解释。

你不能自己编造出生信息、四柱、大运、流年；必须以输入的结构化排盘数据为准。
你的核心任务不是审判命运，而是通过八字、五行、十神、大运、流年等传统命理框架，帮助用户稳定情绪、整理问题、识别倾向和风险，并形成现实可执行的行动建议。

解读原则：
- 本地排盘和 evidence 是唯一依据。
- 你不能编造四柱、大运、流年、十神或地支关系。
- 必须区分排盘事实、命理规则推导、现实建议和不确定项。
- 八字解读只作为传统文化、娱乐性和自我反思参考。
- 不要宣称结果百分百准确。
- 不要把命理结果说成绝对事实。
- 不要说"你一定会失败""你一定会发财""必有大灾"等绝对预测。
- 对学习、竞赛、项目、感情、人际，要给出现实建议。
- 涉及健康、法律、投资等问题时，必须提醒结合现实信息和专业意见。
- 输出必须既解释命理结构，也给出现实行动建议。
"""


def build_bazi_analysis_prompt(chart: dict, focus: str = "综合") -> str:
    return f"""
下面是本地八字排盘结构化数据：
{pformat(chart, width=100)}

本次分析重点：{focus}

请先说明：八字解读只作为传统文化、娱乐性和自我反思参考，不能当作绝对预测。

请按照以下结构输出：

【星图展开】
用一小段有画面感的话概括整体命局气质。

【四柱结构】
解释年柱、月柱、日柱、时柱各自代表的侧重点。不要编造输入数据中没有的信息。

【日主与五行】
解释日主、五行分布、可能的优势与失衡。如果五行统计是粗略版本，请明确说这是初步参考。

【十神倾向】
解释十神体现出的学习、行动、人际、表达、压力处理方式。不要说成绝对性格定论。

【当前阶段】
结合大运、流年或当前年份信息，分析用户当前更适合注意什么。如果大运数据为空，不要硬编，只基于已有流年和命局结构分析。

【现实建议】
给出 3 到 5 条具体可执行建议，优先围绕学习、项目、竞赛、状态管理。

【给用户的一句话】
用温柔但坚定的语气收束。
"""


def build_bazi_question_prompt(chart: dict, question: str, focus: str = "综合") -> str:
    return f"""
下面是本地八字排盘结构化数据：
{pformat(chart, width=100)}

用户的问题：
{question}

问题领域：{focus}

请先说明：这次回答只作为传统文化、娱乐性和自我反思参考，不能替代现实判断或专业建议。

请基于八字结构进行象征性和反思性分析，同时给出现实行动建议。

回答格式：
【问题的核心】
【命局中可以参考的线索】
【需要避开的误区】
【现实中应该怎么做】
【一句提醒】
"""
