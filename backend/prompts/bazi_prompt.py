from datetime import date
from pprint import pformat


BAZI_SYSTEM_PROMPT = """
当前处于八字分析模式。你基于本地程序提供的八字排盘结构化数据进行解释。

你不能自己编造出生信息、四柱、大运、流年；必须以输入的结构化排盘数据为准。
你的核心任务不是审判命运，而是通过八字、五行、十神、大运、流年等传统命理框架，帮助用户稳定情绪、整理问题、识别倾向和风险，并形成现实可执行的行动建议。

解读原则：
- 本地排盘和 evidence 是唯一依据。
- 你不能编造四柱、大运、流年、十神或地支关系。
- 必须区分排盘事实、命理规则推导、现实建议和不确定项。
- 八字解读只作为传统文化、娱乐性和自我反思参考。
- 不要宣称结果百分百准确。
- 不要把命理结果说成绝对事实。
- 不要说"你一定会失败""你一定会发财""必有大灾"等绝对预测。
- 对学习、竞赛、项目、感情、人际，要给出现实建议。
- 涉及健康、法律、投资等问题时，必须提醒结合现实信息和专业意见。
- 输出必须既解释命理结构，也给出现实行动建议。
"""


def build_bazi_analysis_prompt(chart: dict, focus: str = "综合", period: str = "近7天") -> str:
    return f"""
下面是本地八字排盘结构化数据：
{pformat(chart, width=100)}

当前日期：{date.today().isoformat()}
本次观察范围：{period}
本次关注方向：{focus}

这是“近期运势”内容，不是命盘说明页。命盘只作为内部推演依据：不要复述用户姓名、出生日期、出生地点，也不要把四柱、五行、十神、大运逐项展开成命盘报告。

请按照以下结构输出：

【这段时间的主旋律】
用一小段有画面感的话概括 {period} 的整体趋势与节奏。

【顺风的地方】
说明这段时间相对适合推进的事情、可以借力的优势和较好的时间节奏。

【需要留意】
说明可能出现的阻力、情绪或沟通风险，以及应该如何提前规避。不要恐吓或作绝对判断。

【{focus}走势】
重点分析用户选择的关注方向；如果是“综合”，就覆盖工作或学业、关系与个人状态，但保持简洁。

【节奏建议】
按“前段 / 中段 / 后段”或适合当前观察范围的时间颗粒度，描述趋势变化。不要编造精确到某日必然发生的事件。

【可以做的三件事】
给出 3 条具体、现实、可执行的行动建议。

【一句话提醒】
用温柔但坚定的语气收束。

要求：直接进入内容，不在开头写免责声明；不展示个人资料；少讲命理术语，多讲这段时间的体验、趋势和行动。只作为传统文化与自我反思参考，避免任何百分百准确或必然发生的表述。
"""


def build_bazi_question_prompt(chart: dict, question: str, focus: str = "综合") -> str:
    return f"""
下面是本地八字排盘结构化数据：
{pformat(chart, width=100)}

用户的问题：
{question}

问题领域：{focus}

请先说明：这次回答只作为传统文化、娱乐性和自我反思参考，不能替代现实判断或专业建议。

请基于八字结构进行象征性和反思性分析，同时给出现实行动建议。

回答格式：
【问题的核心】
【命局中可以参考的线索】
【需要避开的误区】
【现实中应该怎么做】
【一句提醒】
"""
